// Build-time generation, run automatically on `npm run dev`, `npm run build` and `npm test`:
//  - server/content.generated.ts: everything the /api/chat function needs from the content files (profile text,
//    default site URL, chat limits and error messages), so the API never imports from src/ at runtime.
//  - public/llms.txt: profile.md without its "Rules for the assistant" section, for AI crawlers (served at /llms.txt).
//  - src/link-allowlist.generated.ts: every URL and email in profile.md and content.ts. Bot replies may only link to these
//    (see src/links.ts).
// Reads src/content.ts with Node's built-in TypeScript type stripping (Node 22.18+).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const HEADER = '// GENERATED by scripts/gen-profile.mjs. Do not edit: change content/profile.md or src/content.ts instead.\n';

const writeIfChanged = (file, code) => {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== code) writeFileSync(file, code);
};

// Emails, URLs with a scheme, and bare domains with a path (e.g. "github.com/devashish-1305" in profile.md).
const EMAIL = /[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}/gi;
const URL_RE = /https?:\/\/[^\s<>"'`|)\]]+|(?<![@\w./-])(?:[a-z0-9-]+\.)+[a-z]{2,}\/[^\s<>"'`|)\]]*/gi;
const trim = s => s.replace(/[.,;:!?]+$/, '');

export function extractLinks(text) {
  const emails = [...text.matchAll(EMAIL)].map(m => trim(m[0]));
  const withoutEmails = text.replace(EMAIL, ' ');
  const urls = [...withoutEmails.matchAll(URL_RE)].map(m => trim(m[0]));
  return { emails, urls };
}

/** profile.md minus the "## Rules for the assistant" section (those are instructions for the chatbot, not facts). */
export function toLlmsTxt(profile) {
  return profile.replace(/^## Rules for the assistant\n[\s\S]*?(?=^## )/m, '').replace(/\n{3,}/g, '\n\n');
}

export async function genProfile() {
  const profile = readFileSync(root + 'content/profile.md', 'utf8');
  const { chat, seo } = await import(pathToFileURL(root + 'src/content.ts').href + `?t=${Date.now()}`);
  writeIfChanged(root + 'server/content.generated.ts', [
    HEADER.trimEnd(),
    `export const PROFILE: string = ${JSON.stringify(profile)};`,
    `export const DEFAULT_SITE_URL: string = ${JSON.stringify(seo.defaultSiteUrl)};`,
    `export const CHAT = ${JSON.stringify({ maxChars: chat.maxChars, errors: chat.errors }, null, 2)} as const;`,
    '',
  ].join('\n'));
  writeIfChanged(root + 'public/llms.txt', toLlmsTxt(profile));

  const content = readFileSync(root + 'src/content.ts', 'utf8');
  const a = extractLinks(profile), b = extractLinks(content);
  const urls = [...new Set([...a.urls, ...b.urls])].sort();
  const emails = [...new Set([...a.emails, ...b.emails].map(e => e.toLowerCase()))].sort();
  writeIfChanged(root + 'src/link-allowlist.generated.ts',
    `${HEADER}export const ALLOWED_URLS: string[] = ${JSON.stringify(urls, null, 2)};\nexport const ALLOWED_EMAILS: string[] = ${JSON.stringify(emails, null, 2)};\n`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await genProfile();
